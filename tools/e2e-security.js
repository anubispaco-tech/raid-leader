import { createRequire } from 'module';
import { nav } from './e2e-nav.js';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { playthrough } from './sim-lib.js';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || '/opt/npm-tools/node_modules/playwright');
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = process.argv[2] || 'index.html';
const types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8' };
const G = await import('../src/core/index.js');
const { s } = playthrough({ talents: true, stopAt: 2 });
s.lastSeen = Date.now(); s.player = { pid: 'abcdefgh1234', name: '測試', asked: true, playSec: 0, bindAsked: 1 };
const evil = JSON.parse(JSON.stringify(s));
evil.heroes[0].name = '<img src=x onerror="window.__pwned=1">壞人';
evil.heroes[1].rarity = '"><img src=x onerror="window.__pwned=2">';
const code = Buffer.from(JSON.stringify(evil), 'utf8').toString('base64');
const browser = await chromium.launch(); const page = await browser.newPage({ viewport: { width: 375, height: 760 } }); await page.addInitScript(() => (sessionStorage.setItem('rl-title', '1'), sessionStorage.setItem('rl-e2e', '1')));
const errs = [], csp = []; page.on('pageerror', e => errs.push(e.message)); page.on('console', m => { if (/Content Security Policy/i.test(m.text())) csp.push(m.text()); });
await page.addInitScript(v => { if (!sessionStorage.getItem('seeded')) { localStorage.setItem('raid-leader-save-v1', v); sessionStorage.setItem('seeded', '1'); } }, JSON.stringify(s));
await page.route('**/*', r => { const u = new URL(r.request().url()); if (u.host !== 'app.test') return r.abort();
  const f = path.join(root, u.pathname === '/' ? entry : u.pathname.slice(1));
  return r.fulfill({ body: fs.readFileSync(f), contentType: types[path.extname(f)] }); });
await page.goto('https://app.test/'); await page.waitForTimeout(500);
const fails = [], check = (ok, msg) => { console.log((ok ? '✅ ' : '❌ ') + msg); if (!ok) fails.push(msg); };
check(await page.locator('meta[http-equiv="Content-Security-Policy"]').count() === 1, '頁面有 CSP');
await page.evaluate(() => { const sc = document.createElement('script'); sc.textContent = 'window.__inline = 1'; document.body.appendChild(sc); });
check(!(await page.evaluate(() => window.__inline)), 'CSP 擋掉被插入的 inline script');
// 匯入惡意存檔碼
await page.click('[data-act="settings"]'); await page.waitForTimeout(200);
check((await page.locator('#modal').innerText()).includes('隱私與數據'), '設定有隱私說明');
await page.click('[data-act="import"]'); await page.fill('#impTxt', code); await page.click('[data-act="doimport"]'); await page.waitForTimeout(400);
await page.click('[data-tab="team"]'); await page.waitForTimeout(400);
const html = await page.locator('main').innerHTML();
check(!(await page.evaluate(() => window.__pwned)), '惡意程式碼沒有執行');
check(!html.includes('<img'), '畫面沒有被注入 img 標籤');
check((await page.locator('main').innerText()).includes('壞人'), '名字保留可顯示的文字：' + ((await page.locator('main').innerText()).match(/[^\n]*壞人[^\n]*/) || [''])[0]);
const sv = await page.evaluate(() => JSON.parse(localStorage.getItem('raid-leader-save-v1')));
check(typeof sv.heroes[1].rarity === 'number', '稀有度被修正成數字：' + sv.heroes[1].rarity);
check(!errs.length, '無 JS 錯誤 ' + errs.join(';'));
await browser.close();
if (fails.length) process.exit(1);
